# DOCX — текст для зачитування

def _docx_set_run(run, *, size=12, bold=False, italic=False,
                  font="Times New Roman"):
    run.font.name = font
    run.font.size = DPt(size)
    run.font.bold = bold
    run.font.italic = italic
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:ascii"), font)
    rfonts.set(qn("w:hAnsi"), font)
    rfonts.set(qn("w:cs"), font)


def _docx_para(doc, text, *, size=12, bold=False, italic=False,
               align=None, indent=DCm(1.25), space=DPt(6)):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    if indent is not None:
        pf.first_line_indent = indent
    pf.space_after = space
    pf.line_spacing = 1.5
    run = p.add_run(text)
    _docx_set_run(run, size=size, bold=bold, italic=italic)


def _docx_heading(doc, text, level=1):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = DPt(14)
    pf.space_after = DPt(8)
    pf.keep_with_next = True
    pf.line_spacing = 1.15
    p.alignment = DOCX_ALIGN.CENTER if level == 1 else DOCX_ALIGN.LEFT
    run = p.add_run(text)
    _docx_set_run(run, size=16 if level == 1 else 13, bold=True)


def build_docx() -> Path:
    doc = Document()
    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = DPt(12)
    for section in doc.sections:
        section.left_margin = DCm(2.5)
        section.right_margin = DCm(1.5)
        section.top_margin = DCm(2)
        section.bottom_margin = DCm(2)

    for _ in range(4):
        doc.add_paragraph()
    _docx_para(doc, "ТЕКСТ ДОПОВІДІ", size=20, bold=True,
               align=DOCX_ALIGN.CENTER, indent=None, space=DPt(8))
    _docx_para(doc, "Велика презентація — 20 слайдів",
               size=14, italic=True, align=DOCX_ALIGN.CENTER,
               indent=None, space=DPt(20))
    _docx_para(doc, "Порівняння методів класифікації\n"
                    "з розширеним алгоритмом CMA-ES",
               size=14, bold=True, align=DOCX_ALIGN.CENTER,
               indent=None, space=DPt(60))
    _docx_para(doc, "Богдан Волошенюк",
               size=12, align=DOCX_ALIGN.CENTER,
               indent=None, space=DPt(2))
    _docx_para(doc, "ЧНУ ім. Юрія Федьковича, 2026",
               size=12, align=DOCX_ALIGN.CENTER,
               indent=None, space=DPt(20))
    doc.add_page_break()

    _docx_heading(doc, "Інструкція для доповідача", level=1)
    _docx_para(doc,
        "Тривалість виступу — приблизно 10-12 хвилин при спокійному "
        "темпі мовлення (130 слів на хвилину). На кожен слайд "
        "відведено від 30 до 45 секунд. Перед виступом одноразово "
        "прочитати вголос для відчуття ритму. На захисті рекомендується "
        "використовувати Режим доповідача в PowerPoint — нотатки з "
        "текстом видно лише доповідачу, на основному екрані — сам слайд.")
    _docx_para(doc,
        "На передостанньому слайді — зведений графік порівняння всіх "
        "12 моделей. Біля нього варто зробити паузу і дати комісії "
        "роздивитися. На останньому слайді — QR-код для прямого "
        "переходу на GitHub-репозиторій з кодом проекту. Можна "
        "запропонувати членам комісії відсканувати його зі смартфона.")
    doc.add_page_break()

    _docx_heading(doc, "Суцільний текст доповіді", level=1)
    _docx_para(doc,
        "Версія для тих, хто хоче читати все підряд без перемикання "
        "між слайдами. Між абзацами доцільно робити паузу 2-3 секунди "
        "для переходу на наступний слайд.", italic=True)
    for i, data in enumerate(SLIDES, start=1):
        _docx_para(doc, data["speech"], size=12)
    doc.add_page_break()

    _docx_heading(doc, "Текст по слайдах", level=1)
    for i, data in enumerate(SLIDES, start=1):
        title = data.get("title", "").replace(chr(10), " ")
        _docx_heading(doc, f"Слайд {i}. {title}", level=2)

        if "bullets" in data:
            _docx_para(doc, "Що показано на слайді:",
                       bold=True, indent=None, space=DPt(2))
            for b in data["bullets"]:
                p = doc.add_paragraph()
                pf = p.paragraph_format
                pf.left_indent = DCm(0.75)
                pf.first_line_indent = DCm(-0.5)
                pf.space_after = DPt(3)
                pf.line_spacing = 1.4
                run = p.add_run("•  " + b)
                _docx_set_run(run, size=11)

        if data.get("kind") == "formula_explain":
            _docx_para(doc, "Формула на слайді:",
                       bold=True, indent=None, space=DPt(2))
            _docx_para(doc, data["formula_text"],
                       italic=True, indent=None, space=DPt(2))
            _docx_para(doc, "Опис змінних:",
                       bold=True, indent=None, space=DPt(2))
            for b in data["explanations"]:
                p = doc.add_paragraph()
                pf = p.paragraph_format
                pf.left_indent = DCm(0.75)
                pf.first_line_indent = DCm(-0.5)
                pf.space_after = DPt(3)
                run = p.add_run("•  " + b)
                _docx_set_run(run, size=11)

        if "footer_bullets" in data:
            _docx_para(doc, "Висновки на слайді:",
                       bold=True, indent=None, space=DPt(2))
            for b in data["footer_bullets"]:
                p = doc.add_paragraph()
                pf = p.paragraph_format
                pf.left_indent = DCm(0.75)
                pf.first_line_indent = DCm(-0.5)
                pf.space_after = DPt(3)
                run = p.add_run("•  " + b)
                _docx_set_run(run, size=11)

        _docx_para(doc, "Доповідь:",
                   bold=True, indent=None, space=DPt(2))
        _docx_para(doc, data["speech"], size=12)
        doc.add_paragraph()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    doc.save(str(DOCX_PATH))
    return DOCX_PATH


def main() -> int:
    print(f"Генерую PowerPoint ({len(SLIDES)} слайдів)...")
    pptx_out = build_pptx()
    print(f"  OK: {pptx_out} ({pptx_out.stat().st_size // 1024} KB)")

    print("Генерую текст доповіді (.docx)...")
    docx_out = build_docx()
    print(f"  OK: {docx_out} ({docx_out.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
