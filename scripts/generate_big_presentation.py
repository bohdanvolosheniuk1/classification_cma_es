# PPTX helpers

def _shape_rect(slide, x, y, w, h, fill, line_color=None):
    shape = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, x, y, w, h)
    shape.fill.solid()
    shape.fill.fore_color.rgb = fill
    if line_color is None:
        shape.line.fill.background()
    else:
        shape.line.color.rgb = line_color
    return shape


def _text(slide, x, y, w, h, text, *, size=18, bold=False, color=None,
          align=None, font="Calibri"):
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    tf.margin_left = Cm(0.1)
    tf.margin_right = Cm(0.1)
    lines = text.split("\n")
    for i, line in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        if align is not None:
            p.alignment = align
        run = p.add_run()
        run.text = line
        run.font.name = font
        run.font.size = Pt(size)
        run.font.bold = bold
        if color is not None:
            run.font.color.rgb = color


def _bullets(slide, x, y, w, h, bullets, *, size=15, color=None,
             marker_color=None):
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    tf.margin_left = Cm(0.1)
    for i, line in enumerate(bullets):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = PP_ALIGN.LEFT
        p.space_after = Pt(8)
        # підкреслення для відступленого тексту (починається з пробілів)
        is_sub = line.startswith("    ")
        clean = line.lstrip() if is_sub else line
        if is_sub:
            m_run = p.add_run()
            m_run.text = "        —  "  # відступ + дефіс
            m_run.font.name = "Calibri"
            m_run.font.size = Pt(size - 1)
            m_run.font.color.rgb = COLOR_MUTED
            t_run = p.add_run()
            t_run.text = clean
            t_run.font.name = "Calibri"
            t_run.font.size = Pt(size - 1)
            t_run.font.color.rgb = COLOR_MUTED
        else:
            m_run = p.add_run()
            m_run.text = "■  "
            m_run.font.name = "Calibri"
            m_run.font.size = Pt(size)
            m_run.font.color.rgb = marker_color or COLOR_ACCENT_1
            t_run = p.add_run()
            t_run.text = clean
            t_run.font.name = "Calibri"
            t_run.font.size = Pt(size)
            t_run.font.color.rgb = color or COLOR_TEXT


def _add_speaker_notes(slide, text):
    notes = slide.notes_slide.notes_text_frame
    notes.clear()
    p = notes.paragraphs[0]
    run = p.add_run()
    run.text = text


def _add_header(slide, prs, number, title):
    _shape_rect(slide, Cm(0), Cm(0), prs.slide_width, Cm(1.8),
                fill=COLOR_PRIMARY)
    _text(slide, Cm(0.6), Cm(0.2), Cm(2.5), Cm(1.4),
          number, size=26, bold=True,
          color=COLOR_ACCENT_2, align=PP_ALIGN.LEFT)
    _text(slide, Cm(2.8), Cm(0.4), Cm(20), Cm(1.2),
          title, size=21, bold=True,
          color=COLOR_WHITE, align=PP_ALIGN.LEFT)


def _add_footer(slide, prs):
    _shape_rect(slide, Cm(0), Cm(13.7), prs.slide_width, Cm(0.6),
                fill=COLOR_ACCENT_1)


