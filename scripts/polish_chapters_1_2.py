"""Точкові виправлення розділів 1-2 у backup-файлі диплома.

Не міняє стиль оригіналу Богдана — лише прибирає кричущі помилки:
коректорські описки, звертання на 'ти', неоднорідні форми
'Висновок/Висновки', та найгірші артефакти.

Працює з ``диплом 1_BACKUP_merged.docx`` (об'єднана версія абзаців).
Зберігає у новий файл ``диплом 1_BACKUP_polished.docx``, не зачіпаючи оригіналу.

Запуск::

    python scripts/polish_chapters_1_2.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from docx import Document

REPO_ROOT = Path(__file__).resolve().parent.parent
SRC = REPO_ROOT.parent / "диплом 1_BACKUP_merged.docx"
DST = REPO_ROOT.parent / "диплом 1_BACKUP_polished.docx"


# Точкові заміни. Кожен ключ — оригінальна підрядка, значення — заміна.
# Підрядки мають бути достатньо специфічними, щоб не зловити сторонні випадки.
REPLACEMENTS = [
    # 1. Описка в заголовку 1.3
    ("1.3 Базисні функції в узагальнених адитивних моделя",
     "1.3 Базисні функції в узагальнених адитивних моделях"),

    # 2. Звертання на 'ти' в 1.3
    ("Як приклад, коли підвищуєш ступінь полінома, функція "
     "часто стає нестабільною",
     "Наприклад, при підвищенні ступеня полінома функція "
     "часто стає нестабільною"),

    # 3. Розмовне "Як ми вже зрозуміли"
    ("Як ми вже зрозуміли, сплайни часто використовуються в GAM",
     "Сплайни є одним з ключових інструментів GAM"),

    # 4. Розмовне "На додачу"
    ("На додачу, узагальнені адитивні моделі працюють простіше",
     "Крім того, узагальнені адитивні моделі мають простішу структуру"),

    # 5. Розмовне "Тут навпаки"
    ("Тут навпаки, виникає перенавчання",
     "У такому разі виникає перенавчання"),

    # 6. Однини → множини у форматі заголовків
    ("Висновок до розділу 1", "Висновки до розділу 1"),
    ("Висновок до розділу 2", "Висновки до розділу 2"),

    # 7. Розмовні фрази у 1.4
    ("сплайни приходять на допомогу", "сплайни є природним вибором"),

    # 8. У розділі 2 — побутова метафора "наш обранець"
    ("то це свідчить про те, що наш обранець вартий уваги",
     "це свідчить про перспективність обраного напрямку пошуку"),

    # 9. "В наші дні" — газетна стилістика
    ("В наші дні алгоритм часто використовується",
     "У сучасній практиці алгоритм застосовується"),

    # 10. "Ось чому ми використовуємо його" — розмовне
    ("Класичні підходи не справляються так добре, ось чому ми використовуємо його.",
     "У цих умовах класичні підходи виявляються недостатньо ефективними."),

    # 11. "ось чому" в 2.6
    ("ось чому адаптивне масштабування пошуку значно покращує його роботу.",
     "що пояснює суттєве покращення роботи алгоритму завдяки адаптивному масштабуванню пошуку."),

    # 12. Артефакти в розшифровках 'Де :' / 'де:' — уніфікація
    ("Де :", "Де:"),
]


# Виокремлення заголовків "Висновки до розділу N", що в оригіналі
# приклеїлися до кінця попереднього абзацу. Прибираємо їх з тіла абзацу
# (новий окремий параграф створюється у функції apply_replacements).
HEADING_INLINE = [
    (" Висновок до розділу 1", ""),
    (" Висновки до розділу 1", ""),
    (" Висновок до розділу 2", ""),
    (" Висновки до розділу 2", ""),
]


# Безпідставне "Сучасні дослідження" без посилання — замінюємо
# на нейтральніше "У джерелах за темою" або просто на безособове,
# не міняючи зміст.
SOFT_REPLACEMENTS = [
    ("Сучасні дослідження показують, що вони",
     "Дослідження в галузі показують, що еволюційні алгоритми"),
    ("Сучасні дослідження вважають адаптацію коваріаційної матриці",
     "У літературі за темою адаптацію коваріаційної матриці вважають"),
    ("Дослідники вважають їх використання основою побудови складних",
     "У сучасній літературі їх використання вважається основою побудови складних"),
    ("Дослідження доводять, що сплайни підвищують",
     "Емпіричні результати показують, що сплайни підвищують"),
    ("Сучасні дослідження показують, що алгоритм дає хороші",
     "Експериментальні дослідження показують, що алгоритм забезпечує стабільні"),
]


def apply_replacements(doc: Document) -> int:
    """Заміни виконуються по run'ах, щоб не зруйнувати форматування."""
    count = 0
    all_repls = REPLACEMENTS + SOFT_REPLACEMENTS + HEADING_INLINE

    # Спершу зрозуміємо, після яких параграфів потрібно вставити окремий
    # заголовок (там, де "Висновок/Висновки до розділу N" приліпилось
    # до кінця попереднього абзаца). Перевіряємо ОРИГІНАЛЬНУ форму,
    # бо REPLACEMENTS не виконано ще на цей момент.
    heading_inserts = []  # (index, heading_text)
    for i, p in enumerate(doc.paragraphs):
        full = "".join(r.text for r in p.runs)
        if "Висновок до розділу 1" in full or "Висновки до розділу 1" in full:
            if full.strip().startswith("Висновок") or full.strip().startswith("Висновки"):
                continue  # вже окремий заголовок
            heading_inserts.append((i, "Висновки до розділу 1"))
        elif "Висновок до розділу 2" in full or "Висновки до розділу 2" in full:
            if full.strip().startswith("Висновок") or full.strip().startswith("Висновки"):
                continue
            heading_inserts.append((i, "Висновки до розділу 2"))

    for p in doc.paragraphs:
        full = "".join(r.text for r in p.runs)
        new_full = full
        for old, new in all_repls:
            if old in new_full:
                new_full = new_full.replace(old, new)
                count += 1
        if new_full != full and p.runs:
            p.runs[0].text = new_full
            for r in p.runs[1:]:
                r.text = ""

    # Тепер після кожного потрібного параграфа додаємо окремий заголовок.
    # Робимо це з кінця, щоб індекси не зсувались.
    from docx.oxml.ns import qn
    from copy import deepcopy
    body = doc.element.body
    paragraphs = doc.paragraphs
    for idx, heading in reversed(heading_inserts):
        # Створюємо новий параграф з жирним заголовком на основі
        # клону поточного, щоб успадкувати стиль абзацу.
        src = paragraphs[idx]._p
        new_p = deepcopy(src)
        # Чистимо всі run'и в клоні
        for r in new_p.findall(qn("w:r")):
            new_p.remove(r)
        # Додаємо новий run з жирним заголовком
        from docx.oxml import OxmlElement
        new_r = OxmlElement("w:r")
        new_rpr = OxmlElement("w:rPr")
        b = OxmlElement("w:b")
        new_rpr.append(b)
        sz = OxmlElement("w:sz")
        sz.set(qn("w:val"), "28")
        new_rpr.append(sz)
        new_r.append(new_rpr)
        t = OxmlElement("w:t")
        t.text = heading
        new_r.append(t)
        new_p.append(new_r)
        # Вставляємо після поточного
        src.addnext(new_p)
        count += 1
    return count


def main() -> int:
    if not SRC.exists():
        print(f"ПОМИЛКА: не знайдено {SRC}", file=sys.stderr)
        return 1

    doc = Document(SRC)
    n = apply_replacements(doc)
    doc.save(DST)
    print(f"Виконано {n} замін")
    print(f"Збережено: {DST.name} ({DST.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
