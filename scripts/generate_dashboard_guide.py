def _set_run(run, *, size=12, bold=False, italic=False,
             font="Times New Roman", color=None):
    run.font.name = font
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:ascii"), font)
    rfonts.set(qn("w:hAnsi"), font)
    rfonts.set(qn("w:cs"), font)


def _para(doc, text, *, size=12, bold=False, italic=False, align=None,
          indent=Cm(1.25), space=Pt(6)):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    if indent is not None:
        pf.first_line_indent = indent
    pf.space_after = space
    pf.line_spacing = 1.5
    run = p.add_run(text)
    _set_run(run, size=size, bold=bold, italic=italic)
    return p


def _h(doc, text, level=1):
    sizes = {1: 16, 2: 14, 3: 13}
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT if level > 1 else WD_ALIGN_PARAGRAPH.CENTER
    pf = p.paragraph_format
    pf.space_before = Pt(18 if level == 1 else 12 if level == 2 else 8)
    pf.space_after = Pt(10 if level == 1 else 6 if level == 2 else 4)
    pf.line_spacing = 1.15
    pf.keep_with_next = True
    run = p.add_run(text)
    _set_run(run, size=sizes.get(level, 12), bold=True,
             color=RGBColor(0x26, 0x46, 0x53) if level == 1 else None)


def _bullet(doc, text, *, size=12):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.4
    run = p.add_run(text)
    _set_run(run, size=size)


def _code(doc, text):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.left_indent = Cm(0.5)
    pf.space_after = Pt(6)
    pf.line_spacing = 1.15
    for i, line in enumerate(text.split("\n")):
        if i > 0:
            p.add_run().add_break()
        run = p.add_run(line)
        _set_run(run, size=10, font="Consolas",
                 color=RGBColor(0x33, 0x33, 0x33))


def _table(doc, headers, rows, widths=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Light Grid"
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(h)
        _set_run(run, size=11, bold=True)
    for r_i, row in enumerate(rows, start=1):
        for c_i, val in enumerate(row):
            cell = table.rows[r_i].cells[c_i]
            cell.text = ""
            run = cell.paragraphs[0].add_run(str(val))
            _set_run(run, size=11)
    if widths is not None:
        for row in table.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()


def _element_block(doc, name, *, what, source, why, example=None):
    """Стандартний блок опису елемента дашборду."""
    _h(doc, name, level=3)
    _para(doc, "Що це робить:", bold=True, indent=None, space=Pt(2))
    _para(doc, what)
    _para(doc, "На основі чого:", bold=True, indent=None, space=Pt(2))
    _para(doc, source)
    _para(doc, "Чому саме так:", bold=True, indent=None, space=Pt(2))
    _para(doc, why)
    if example is not None:
        _para(doc, "Приклад:", bold=True, indent=None, space=Pt(2))
        _para(doc, example, italic=True)


def _page_break(doc):
    doc.add_page_break()


