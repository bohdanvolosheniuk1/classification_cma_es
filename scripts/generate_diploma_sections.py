def _set_run(run, *, size=14, bold=False, italic=False,
             font="Times New Roman"):
    run.font.name = font
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:ascii"), font)
    rfonts.set(qn("w:hAnsi"), font)
    rfonts.set(qn("w:cs"), font)


def _p(doc, text, *, size=14, bold=False, italic=False, align=None,
       indent=Cm(1.25), space=Pt(6)):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    if indent is not None:
        pf.first_line_indent = indent
    pf.space_after = space
    pf.line_spacing = 1.5
    run = p.add_run(text)
    _set_run(run, size=size, bold=bold, italic=italic)


def _h(doc, text, level=1):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(18 if level == 1 else 12)
    pf.space_after = Pt(12 if level == 1 else 8)
    pf.keep_with_next = True
    pf.line_spacing = 1.5
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if level == 1 else WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run(text)
    _set_run(run, size=14, bold=True)


def _bullet(doc, text):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.left_indent = Cm(0.75)
    pf.first_line_indent = Cm(-0.5)
    pf.space_after = Pt(4)
    pf.line_spacing = 1.5
    run = p.add_run("•  " + text)
    _set_run(run, size=14)


def _table(doc, headers, rows, widths=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    # стиль "Light Grid" може бути відсутній в оригінальному документі Богдана,
    # тому застосовуємо м'яко через try/except
    try:
        table.style = "Light Grid"
    except KeyError:
        try:
            table.style = "Table Grid"
        except KeyError:
            pass  # буде дефолтна без рамок
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(h)
        _set_run(run, size=12, bold=True)
    for r_i, row in enumerate(rows, start=1):
        for c_i, val in enumerate(row):
            cell = table.rows[r_i].cells[c_i]
            cell.text = ""
            run = cell.paragraphs[0].add_run(str(val))
            _set_run(run, size=12)
    if widths is not None:
        for row in table.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()


def _image(doc, path: Path, *, width_cm=14, caption=None):
    if not path.exists():
        _p(doc, f"[Рисунок недоступний: {path.name}]", italic=True, indent=None)
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(str(path), width=Cm(width_cm))
    if caption:
        cp = doc.add_paragraph()
        cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        cp.paragraph_format.space_after = Pt(10)
        run = cp.add_run(caption)
        _set_run(run, size=12, italic=True)


