def _caption(doc, text: str):
    """Підпис під формулою – курсив по центру."""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.line_spacing = 1.15
    run = p.add_run(text)
    _set_run(run, size=12, italic=True)


def _where_intro(doc):
    """Параграф 'Де:' перед списком змінних формули."""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.line_spacing = 1.5
    run = p.add_run("Де:")
    _set_run(run, size=14)


def _var_def(doc, symbol_runs, definition: str):
    """Один рядок-визначення змінної формули.

    Приклад виклику::

        _var_def(doc, [("β", False), ("0", True)],
                 "вільний член моделі")

    Кожен елемент symbol_runs – це (текст, is_subscript). Дозволяє
    зробити nested-індекси типу β₀ через subscript-run у Word.
    """
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.left_indent = Cm(0.75)
    pf.first_line_indent = Cm(-0.5)
    pf.space_after = Pt(3)
    pf.line_spacing = 1.4
    # маркер
    marker = p.add_run("–  ")
    _set_run(marker, size=14)
    # сам символ зі змінною з підіндексами
    for text, is_sub in symbol_runs:
        r = p.add_run(text)
        _set_run(r, size=14, italic=not is_sub)
        if is_sub:
            r.font.subscript = True
    # тире і визначення
    dash = p.add_run(" – ")
    _set_run(dash, size=14)
    descr = p.add_run(definition)
    _set_run(descr, size=14)


def _add_block_formula(doc, *children):
    """Додає блочну OMML-формулу і налаштовує її параграф.

    Використовується для inline-математики у визначеннях. Для блочних
    формул розділу 3 застосовуємо PNG через _png_formula – це гарантує
    відображення в усіх версіях Word, LibreOffice та при PDF-конвертації.
    """
    p = omml.add_block_formula(doc, *children)
    pf = p.paragraph_format
    pf.space_before = Pt(6)
    pf.space_after = Pt(2)
    pf.line_spacing = 1.5
    return p


def _png_formula(doc, png_name: str, number: str, *, width_cm: float = 12.0):
    """Вставляє формулу як PNG із номером праворуч.

    Структура: центрований параграф з картинкою + табуляція + номер
    у форматі (N.M). Це формат, який повністю сумісний з усіма
    рендерерами Word та PDF-конвертерами.
    """
    path = FIGURES_DIR / png_name
    if not path.exists():
        _p(doc, f"[Формула недоступна: {png_name}]", italic=True, indent=None)
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pf = p.paragraph_format
    pf.space_before = Pt(6)
    pf.space_after = Pt(6)
    # tab stop праворуч для номера формули
    pf.tab_stops.add_tab_stop(Cm(16.0), WD_ALIGN_PARAGRAPH.RIGHT)
    # картинка по центру
    run_pic = p.add_run()
    run_pic.add_picture(str(path), width=Cm(width_cm))
    # таб + номер праворуч
    run_num = p.add_run(f"\t{number}")
    _set_run(run_num, size=14)


