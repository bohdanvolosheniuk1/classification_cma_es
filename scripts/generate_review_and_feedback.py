"""Генерує Рецензію і Відгук на дипломну роботу Богдана.

Структура і стиль повторюють зразки «Рецензія Владарчук.docx» і
«Відгук Владарчук.docx» з адаптацією під тему і зміст роботи Богдана:
«Порівняння методів класифікації з розширеним алгоритмом CMA-ES».
"""

from __future__ import annotations

import sys
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement
from docx.shared import Cm, Pt


REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_REVIEW = REPO_ROOT.parent / "Рецензія Волошенюк.docx"
OUT_FEEDBACK = REPO_ROOT.parent / "Відгук Волошенюк.docx"


def _set_run(run, *, size=14, bold=False, italic=False,
             font="Times New Roman"):
    run.font.name = font
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:ascii"), font)
    rfonts.set(qn("w:hAnsi"), font)
    rfonts.set(qn("w:cs"), font)


def _para(doc, text, *, size=14, bold=False, italic=False,
          align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=Cm(1.25),
          space=Pt(6)):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    if indent is not None:
        pf.first_line_indent = indent
    pf.space_after = space
    pf.line_spacing = 1.5
    run = p.add_run(text)
    _set_run(run, size=size, bold=bold, italic=italic)
    return p


def _setup_page(doc):
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)
    for section in doc.sections:
        section.left_margin = Cm(2.5)
        section.right_margin = Cm(1.5)
        section.top_margin = Cm(2)
        section.bottom_margin = Cm(2)


def _header_block(doc, header_word: str):
    """Шапка документа: тип роботи + рівень + тема + ПІБ + група + вуз."""
    # тип ("Рецензія" або "ВІДГУК")
    _para(doc, header_word,
          size=14, bold=True,
          align=WD_ALIGN_PARAGRAPH.CENTER,
          indent=None, space=Pt(6))
    _para(doc,
          "на дипломний проєкт першого (бакалаврського) рівня вищої освіти",
          size=14, align=WD_ALIGN_PARAGRAPH.CENTER,
          indent=None, space=Pt(6))
    _para(doc,
          "«Порівняння методів класифікації з розширеним алгоритмом CMA-ES»",
          size=14, bold=True, italic=True,
          align=WD_ALIGN_PARAGRAPH.CENTER,
          indent=None, space=Pt(6))
    _para(doc,
          "Волошенюка Богдана Анатолійовича,",
          size=14, align=WD_ALIGN_PARAGRAPH.CENTER,
          indent=None, space=Pt(2))
    _para(doc,
          "студента 441-А групи спеціальності 122 – «Комп'ютерні науки»",
          size=14, align=WD_ALIGN_PARAGRAPH.CENTER,
          indent=None, space=Pt(2))
    _para(doc,
          "Навчально-наукового інституту фізико-технічних "
          "та комп'ютерних наук",
          size=14, align=WD_ALIGN_PARAGRAPH.CENTER,
          indent=None, space=Pt(2))
    _para(doc,
          "Чернівецького національного університету імені Юрія Федьковича",
          size=14, align=WD_ALIGN_PARAGRAPH.CENTER,
          indent=None, space=Pt(18))


def _signature_block(doc, lines):
    """Підпис рецензента/керівника праворуч."""
    for i, line in enumerate(lines):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        pf = p.paragraph_format
        pf.first_line_indent = Cm(0)
        pf.space_after = Pt(2)
        pf.line_spacing = 1.3
        run = p.add_run(line)
        _set_run(run, size=14)


