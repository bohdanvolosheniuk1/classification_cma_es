def _font_paths() -> tuple[Path, Path]:
    """Шлях до DejaVu Sans (звичайний і жирний) із бандла matplotlib."""
    data = Path(matplotlib.get_data_path()) / "fonts" / "ttf"
    return data / "DejaVuSans.ttf", data / "DejaVuSans-Bold.ttf"


class GuidePDF(FPDF):
    def __init__(self):
        super().__init__(orientation="P", unit="mm", format="A4")
        reg, bold = _font_paths()
        self.add_font("DejaVu", "", str(reg))
        self.add_font("DejaVu", "B", str(bold))
        self.set_auto_page_break(auto=True, margin=20)
        self.set_margins(20, 20, 20)
        self.alias_nb_pages()

    def header(self):
        if self.page_no() == 1:
            return
        self.set_font("DejaVu", "", 9)
        self.set_text_color(120, 120, 120)
        self.cell(0, 8, "classification_cma_es — гайд для Богдана",
                  border=0, align="L")
        self.cell(0, 8, f"стор. {self.page_no()} / {{nb}}",
                  border=0, align="R", new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(0, 0, 0)
        self.ln(2)

    def title_page(self) -> None:
        self.add_page()
        self.ln(50)
        self.set_font("DejaVu", "B", 26)
        self.cell(0, 14, "classification_cma_es",
                  align="C", new_x="LMARGIN", new_y="NEXT")
        self.ln(4)
        self.set_font("DejaVu", "", 14)
        self.cell(0, 8, "Як працює програма — гайд для Богдана",
                  align="C", new_x="LMARGIN", new_y="NEXT")
        self.ln(40)
        self.set_font("DejaVu", "", 11)
        self.set_text_color(80, 80, 80)
        self.multi_cell(
            0, 6,
            "Практична частина дипломної роботи: порівняння класифікаторів "
            "із застосуванням розширеного алгоритму CMA-ES (за роботою "
            "Літвінчук Ю.А., 2024) та узагальнених адитивних моделей (GAM) "
            "з розділу 1 диплома.\n\n"
            "У цьому документі — пояснення кожної частини програми, "
            "схематичні діаграми та інструкції з запуску.",
            align="C",
        )
        self.set_text_color(0, 0, 0)
        self.ln(60)
        self.set_font("DejaVu", "", 9)
        self.cell(0, 6, "Чернівецький національний університет",
                  align="C", new_x="LMARGIN", new_y="NEXT")
        self.cell(0, 6, "Кафедра прикладної математики та інформаційних технологій",
                  align="C", new_x="LMARGIN", new_y="NEXT")

    def h1(self, text: str) -> None:
        self.ln(4)
        self.set_font("DejaVu", "B", 18)
        self.set_text_color(38, 70, 83)
        self.multi_cell(0, 10, text, new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(0, 0, 0)
        self.ln(2)

    def h2(self, text: str) -> None:
        self.ln(2)
        self.set_font("DejaVu", "B", 13)
        self.set_text_color(42, 157, 143)
        self.multi_cell(0, 7, text, new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(0, 0, 0)
        self.ln(1)

    def body(self, text: str) -> None:
        self.set_font("DejaVu", "", 11)
        self.multi_cell(0, 5.5, text, new_x="LMARGIN", new_y="NEXT")
        self.ln(2)

    def bullets(self, items: list[str]) -> None:
        self.set_font("DejaVu", "", 11)
        for it in items:
            self.cell(6, 5.5, "•", new_x="RIGHT", new_y="TOP")
            self.multi_cell(0, 5.5, it, new_x="LMARGIN", new_y="NEXT")
        self.ln(1)

    def code(self, text: str) -> None:
        self.set_font("DejaVu", "", 10)
        self.set_fill_color(245, 245, 245)
        for line in text.split("\n"):
            self.cell(0, 5, "  " + line, new_x="LMARGIN", new_y="NEXT",
                      fill=True)
        self.ln(2)

    def image_centered(self, path: Path, w_mm: float = 170) -> None:
        try:
            page_w = self.w - self.l_margin - self.r_margin
            x = self.l_margin + (page_w - w_mm) / 2
            self.image(str(path), x=x, w=w_mm)
            self.ln(3)
        except Exception as e:
            self.body(f"[не вдалося вставити рисунок: {path.name} — {e}]")

    def caption(self, text: str) -> None:
        self.set_font("DejaVu", "", 9)
        self.set_text_color(100, 100, 100)
        self.cell(0, 5, text, align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(0, 0, 0)
        self.ln(3)


